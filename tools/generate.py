#!/usr/bin/env python3
"""
Generate the Rust layout table and the XKB symbols file from the public
m17n Unijoy (Bijoy) input method definition.

Source: /usr/share/m17n/bn-unijoy.mim  (m17n-db, LGPL-2.1)
        Copyright (C) 2005, 2008 AIST

Usage: python3 tools/generate.py [path-to-bn-unijoy.mim]
Writes: src/layout.rs and xkb/symbols/bijoy
"""
import os
import re
import sys

MIM = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/m17n/bn-unijoy.mim"
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def unescape(s):
    """Decode m17n key escaping: backslash before a char yields that char."""
    out = []
    i = 0
    while i < len(s):
        if s[i] == "\\" and i + 1 < len(s):
            out.append(s[i + 1])
            i += 2
        else:
            out.append(s[i])
            i += 1
    return "".join(out)


def rust_escape(s):
    return "".join("\\u{%04X}" % ord(c) for c in s)


def parse():
    base = []        # (key, value) unshifted
    shift = []       # (key, value) shifted result char
    altgr = []       # (key, value) AltGr layer
    dead = []        # dead keys: (key, value)
    independent = []  # (key, value) produced after the hasanta dead key
    section = None
    for line in open(MIM, encoding="utf-8"):
        s = line.split(";;")[0].strip()
        if not s:
            continue
        if s.startswith("(livekey"):
            section = "livekey"
            continue
        if s.startswith("(deadkey"):
            section = "deadkey"
            continue
        if s.startswith("(independent"):
            section = "independent"
            continue
        if s.startswith(")"):
            section = None
            continue

        if section == "livekey":
            m = re.match(r'^\(\s*"((?:[^"\\]|\\.)*)"\s+"(.*)"\s*\)$', s)
            if m:
                key, val = unescape(m.group(1)), m.group(2)
                if len(key) == 1:
                    if key.isupper() or key in "~$^&*|":
                        shift.append((key, val))
                    else:
                        base.append((key, val))
                continue
            m = re.match(r"^\(\(A-(.+)\)\s+\"(.*)\"\s*\)$", s)
            if m:
                key, val = unescape(m.group(1)), m.group(2)
                altgr.append((key, val))
        elif section == "deadkey":
            m = re.match(r'^\(\s*"((?:[^"\\]|\\.)*)"\s+"(.*)"\s*\)$', s)
            if m:
                dead.append((unescape(m.group(1)), m.group(2)))
        elif section == "independent":
            m = re.match(r'^\(\s*"((?:[^"\\]|\\.)*)"\s+\(delete @-\)\s+"(.*)"\s*\)$', s)
            if m:
                independent.append((unescape(m.group(1)), m.group(2)))
    return base, shift, altgr, dead, independent


def write_rust(base, shift, altgr, dead, independent):
    out = []
    out.append("// Generated by tools/generate.py from bn-unijoy.mim (m17n-db, LGPL-2.1).")
    out.append("// Do not edit by hand; regenerate with: python3 tools/generate.py")
    out.append("")

    def rkey(k):
        if k == "\\":
            return "\\\\"
        if k == '"':
            return '\\"'
        return k

    def emit(name, rows):
        out.append("pub const %s: &[(&str, &str)] = &[" % name)
        for k, v in rows:
            out.append('    ("%s", "%s"),' % (rkey(k), rust_escape(v)))
        out.append("];")
        out.append("")

    emit("BASE", base)
    emit("SHIFT", shift)
    emit("ALTGR", altgr)
    emit("DEAD", dead)
    emit("INDEPENDENT", independent)
    path = os.path.join(ROOT, "src", "layout.rs")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", path)


# ---- XKB generation --------------------------------------------------------

# US QWERTY physical key -> (level1 char, level2 char)
US = {
    "<TLDE>": ("`", "~"),
    "<AE01>": ("1", "!"), "<AE02>": ("2", "@"), "<AE03>": ("3", "#"),
    "<AE04>": ("4", "$"), "<AE05>": ("5", "%"), "<AE06>": ("6", "^"),
    "<AE07>": ("7", "&"), "<AE08>": ("8", "*"), "<AE09>": ("9", "("),
    "<AE10>": ("0", ")"), "<AE11>": ("-", "_"), "<AE12>": ("=", "+"),
    "<AD01>": ("q", "Q"), "<AD02>": ("w", "W"), "<AD03>": ("e", "E"),
    "<AD04>": ("r", "R"), "<AD05>": ("t", "T"), "<AD06>": ("y", "Y"),
    "<AD07>": ("u", "U"), "<AD08>": ("i", "I"), "<AD09>": ("o", "O"),
    "<AD10>": ("p", "P"), "<AD11>": ("[", "{"), "<AD12>": ("]", "}"),
    "<BKSL>": ("\\", "|"),
    "<AC01>": ("a", "A"), "<AC02>": ("s", "S"), "<AC03>": ("d", "D"),
    "<AC04>": ("f", "F"), "<AC05>": ("g", "G"), "<AC06>": ("h", "H"),
    "<AC07>": ("j", "J"), "<AC08>": ("k", "K"), "<AC09>": ("l", "L"),
    "<AC10>": (";", ":"), "<AC11>": ("'", '"'),
    "<AB01>": ("z", "Z"), "<AB02>": ("x", "X"), "<AB03>": ("c", "C"),
    "<AB04>": ("v", "V"), "<AB05>": ("b", "B"), "<AB06>": ("n", "N"),
    "<AB07>": ("m", "M"), "<AB08>": (",", "<"), "<AB09>": (".", ">"),
    "<AB10>": ("/", "?"),
}

KEYSYM = {
    "!": "exclam", "@": "at", "#": "numbersign", "$": "dollar", "%": "percent",
    "^": "asciicircum", "&": "ampersand", "*": "asterisk", "(": "parenleft",
    ")": "parenright", "-": "minus", "_": "underscore", "=": "equal",
    "+": "plus", "[": "bracketleft", "]": "bracketright", "{": "braceleft",
    "}": "braceright", "\\": "backslash", "|": "bar", ";": "semicolon",
    ":": "colon", "'": "apostrophe", '"': "quotedbl", "`": "grave",
    "~": "asciitilde", ",": "comma", "<": "less", ".": "period", ">": "greater",
    "/": "slash", "?": "question",
}


def ksym(ch):
    if ord(ch) < 128:
        if ch.isalnum():
            return ch
        return KEYSYM[ch]
    return "U%04X" % ord(ch)


def write_xkb(base, shift, altgr, dead):
    # The hasanta dead key `g` types hasanta as a plain key in XKB
    # (XKB cannot express the dead-key + independent-vowel behavior).
    base_m = dict(base)
    base_m.update(dict(dead))
    shift_m = dict(shift)

    unshifted_kc = {c: kc for kc, (c, _) in US.items()}
    shifted_kc = {c: kc for kc, (_, c) in US.items()}

    # AltGr: unshifted key -> level3, shifted key -> level4.
    altgr_l3 = {}
    altgr_l4 = {}
    altgr_key = {}
    for k, v in altgr:
        if k in unshifted_kc:
            kc = unshifted_kc[k]
            altgr_l3[kc] = v
            altgr_key[(kc, 3)] = k
        elif k in shifted_kc:
            kc = shifted_kc[k]
            altgr_l4[kc] = v
            altgr_key[(kc, 4)] = k

    kcs = set()
    for k in base_m:
        if k in unshifted_kc:
            kcs.add(unshifted_kc[k])
    for k in shift_m:
        if k in shifted_kc:
            kcs.add(shifted_kc[k])
    kcs |= set(altgr_l3) | set(altgr_l4)

    order = sorted(kcs, key=lambda k: (k[:3], int(k[3:5])) if k[3:5].isdigit() else (k, 0))

    lines = []
    lines.append("// Bijoy (Unijoy) Bangla keyboard layout.")
    lines.append("// Generated by tools/generate.py from bn-unijoy.mim (m17n-db, LGPL-2.1).")
    lines.append("// Install to /usr/share/X11/xkb/symbols/bijoy and register in rules/evdev.xml.")
    lines.append("")
    lines.append("partial default alphanumeric_keys")
    lines.append('xkb_symbols "bijoy" {')
    lines.append('    include "us"')
    lines.append('    name[Group1]= "Bijoy (Unijoy)";')
    lines.append("")

    multi_notes = []

    def one(p, keychar):
        if p is not None and len(p) > 1:
            multi_notes.append((keychar, p, p[0]))
            return p[0]
        return p

    for kc in order:
        l1, l2 = US[kc]
        l1v = base_m.get(l1, l1)
        l2v = shift_m.get(l2, l2)
        l3v = altgr_l3.get(kc)
        l4v = altgr_l4.get(kc)

        c1 = one(l1v, l1)
        c2 = one(l2v, l2)
        c3 = one(l3v, altgr_key.get((kc, 3), "?"))
        c4 = one(l4v, altgr_key.get((kc, 4), "?"))

        levels = [c1, c2]
        if c3 is not None or c4 is not None:
            levels.append(c3 if c3 is not None else "NoSymbol")
        if c4 is not None:
            levels.append(c4)

        def render(p):
            return p if p == "NoSymbol" else ksym(p)

        ks = ", ".join(render(p) for p in levels)
        comment = ""
        if c1 != l1:
            comment += " %s->%s" % (l1, l1v)
        if c2 != l2:
            comment += " %s->%s" % (l2, l2v)
        if l3v is not None:
            comment += " AltGr+%s->%s" % (altgr_key.get((kc, 3), "?"), l3v)
        if l4v is not None:
            comment += " AltGr+%s->%s" % (altgr_key.get((kc, 4), "?"), l4v)
        trailing = (" //" + comment) if comment else ""
        lines.append("    key %s { [ %s ] };%s" % (kc, ks, trailing))
        lines.append("")

    lines.append('    include "level3(ralt_switch)"')
    lines.append("};")
    lines.append("")

    if multi_notes:
        lines.append("// NOTE: these keys type only their first code point here because an XKB")
        lines.append("// keysym is a single code point. The full two-code-point Bijoy output is")
        lines.append("// available through the `bijoy type` tool or an input method engine:")
        for keychar, full, first in multi_notes:
            lines.append("//   (%s) -> %s  (typed here as %s)"
                         % (keychar,
                            " ".join("U+%04X" % ord(c) for c in full),
                            "U+%04X" % ord(first)))
        lines.append("")

    path = os.path.join(ROOT, "xkb", "symbols", "bijoy")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("wrote", path)


if __name__ == "__main__":
    base, shift, altgr, dead, independent = parse()
    print("parsed %s: base=%d shift=%d altgr=%d dead=%d independent=%d"
          % (MIM, len(base), len(shift), len(altgr), len(dead), len(independent)))
    write_rust(base, shift, altgr, dead, independent)
    write_xkb(base, shift, altgr, dead)
